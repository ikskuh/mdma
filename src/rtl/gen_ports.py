"""Emit the Verilog port decoder from the assembler's ISA tables."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "pylibs"))
from mdma import SINK_BY_INDEX, SINK_BY_NAME, SOURCE_BY_INDEX


def lookup(name, output_width, input_width, values, default=0):
    print(f"function [{output_width - 1}:0] {name}(input [{input_width - 1}:0] index);")
    print("    case (index)")
    for index, value in values.items():
        print(f"        {input_width}'d{index}: {name} = {output_width}'d{value};")
    print(f"        default: {name} = {output_width}'d{default};")
    print("    endcase")
    print("endfunction")
    print()


def main():
    sinks = {}
    sources = {}
    for port in SINK_BY_INDEX.values():
        if port.unit.unit.name != "CPU":
            sinks.setdefault(port.unit, []).append(port.index)
    for port in SOURCE_BY_INDEX.values():
        if port.unit in sinks:
            sources.setdefault(port.unit, []).append(port.index)
    units = list(sinks)
    print("// Generated by gen_ports.py from src/pylibs/mdma.py.")
    print(f"localparam [5:0] SINK_PC_REL = 6'd{SINK_BY_NAME['CPU.PC_REL'].index};")
    for index, unit in enumerate(units):
        print(f"localparam [4:0] FU_{unit} = 5'd{index};")
    print(f"localparam [4:0] FU_COUNT = 5'd{len(units)};")
    lookup("fu_base", 6, 5, {i: min(sinks[unit]) for i, unit in enumerate(units)})
    lookup("fu_inputs", 3, 5, {i: len(sinks[unit]) for i, unit in enumerate(units)})
    lookup("fu_outputs", 3, 5, {i: len(sources[unit]) for i, unit in enumerate(units)})
    lookup("source_fu", 5, 6, {port: i for i, unit in enumerate(units) for port in sources[unit]}, default=31)
    lookup("fu_source", 6, 8,
           {(i << 3) | lane: port for i, unit in enumerate(units) for lane, port in enumerate(sources[unit])})


if __name__ == "__main__":
    main()
